import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transform } from 'esbuild';
import { legacySupport, legacyAssets, auditLegacyAssets, REMOTE_DRACO, DRACO_PREFIX } from './legacy-assets.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const id = resolve(root, 'src/libs/xviewer/xviewer.module.min.js');
const source = await readFile(id, 'utf8');
const plugin = legacySupport();
assert.equal(plugin.apply, 'serve', 'default campus config must only enable legacy support in dev');
assert.equal(plugin.transform('unchanged', resolve(root, 'src/campus/scene.ts')), null, 'campus source cannot be transformed');
const changed = plugin.transform.call({ error(message) { throw new Error(message); } }, source, id);
assert.ok(!changed.code.includes(REMOTE_DRACO), 'external decoder URL must be removed from served legacy code');
assert.ok(changed.code.includes(DRACO_PREFIX), 'decoder base must be same-origin');
await transform(changed.code, { loader: 'js', target: 'es2020' });
assert.equal(await readFile(id, 'utf8'), source, 'shared upstream source must not change');
const entries = legacyAssets(root);
assert.equal(entries.filter(entry => entry.fileName.startsWith('Genshin/')).length, 31);
assert.equal(entries.filter(entry => entry.fileName.includes('draco') && (entry.fileName.endsWith('.wasm') || entry.fileName.endsWith('.js'))).length, 3);
assert.ok(!entries.some(entry => entry.fileName.startsWith('campus/')), 'legacy build does not copy campus resources');
const audit = await auditLegacyAssets(root);
assert.equal(audit.gameBytes, 7886601);
assert.equal(audit.publicationStatus, 'blocked-pending-third-party-rights-review');
let middleware;
plugin.configResolved({ root, command: 'serve' });
plugin.configureServer({ middlewares: { use(callback) { middleware = callback; } } });
const request = async (url, method = 'GET') => {
  const reply = { statusCode: 200, headers: {}, data: undefined, next: false, setHeader(name, value) { this.headers[name] = value; }, end(data) { this.data = data; } };
  await middleware({ url, method }, reply, () => { reply.next = true; }); return reply;
};
const wasm = await request('/_legacy-draco/draco_decoder.wasm');
assert.equal(wasm.statusCode, 200); assert.equal(wasm.headers['Content-Type'], 'application/wasm'); assert.ok(wasm.data.length > 1000);
assert.equal((await request('/_legacy-draco/private.txt')).statusCode, 404);
assert.equal((await request('/_legacy-draco/draco_decoder.wasm', 'POST')).statusCode, 405);
assert.equal((await request('/campus-fallback.svg')).next, true, 'middleware must not own campus URLs');
assert.equal((await request('/_legacy-draco/draco_decoder.js', 'HEAD')).data, undefined);
console.log('PASS: decoder transform, untouched upstream/campus, whitelist, byte count, license gate, same-origin middleware MIME/method/path controls');
